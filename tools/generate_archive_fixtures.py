"""Generate small synthetic IWD fixtures with independent Python ZIP/zlib code."""

import argparse
from io import BytesIO
from pathlib import Path
import struct
import warnings
import zipfile


ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "crates/content/tests/fixtures/archives.txt"


def archive(entries: list[tuple[str, bytes, int]], force_zip64=False) -> bytes:
    stream = BytesIO()
    with warnings.catch_warnings():
        warnings.simplefilter("ignore", UserWarning)
        with zipfile.ZipFile(stream, "w") as writer:
            for name, payload, method in entries:
                info = zipfile.ZipInfo(name, (2026, 1, 1, 0, 0, 0))
                info.compress_type = method
                info.create_system = 3
                info.external_attr = 0o100644 << 16
                with writer.open(info, "w", force_zip64=force_zip64) as entry:
                    entry.write(payload)
    return stream.getvalue()


def changed(data: bytes, offset: int, value: bytes) -> bytes:
    result = bytearray(data)
    result[offset:offset + len(value)] = value
    return bytes(result)


def zip64_footer(data: bytes) -> bytes:
    end = len(data) - 22
    fields = struct.unpack_from("<4s4H2IH", data, end)
    count, size, start = fields[4], fields[5], fields[6]
    record = struct.pack(
        "<4sQ2H2I4Q", b"PK\x06\x06", 44, 45, 45, 0, 0,
        count, count, size, start
    )
    locator = struct.pack("<4sIQI", b"PK\x06\x07", 0, end, 1)
    footer = struct.pack(
        "<4s4H2IH", b"PK\x05\x06", 0, 0, 0xffff, 0xffff,
        0xffffffff, 0xffffffff, 0
    )
    return data[:end] + record + locator + footer


def fixtures() -> dict[str, bytes]:
    stored, deflated = zipfile.ZIP_STORED, zipfile.ZIP_DEFLATED
    single = archive([("images/SECRET.iwi", b"secret-image-data", stored)])
    central = single.index(b"PK\x01\x02")
    data_start = 30 + len("images/SECRET.iwi")
    baseline = archive([
        ("images/", b"", stored),
        ("images/Badge.iwi", b"old", stored),
        ("IMAGES\\BADGE.iwi", b"middle", deflated),
        ("images/Badge.iwi", b"last", deflated),
        ("scripts/example.gsc", b"print(\"synthetic\");\n" * 30, deflated),
        ("empty.bin", b"", stored),
        ("long/" + "x" * 150, bytes(range(256)), stored),
    ])
    result = {
        "baseline": baseline,
        "single": single,
        "empty": archive([]),
        "zip64": zip64_footer(baseline),
        "zip64_local": archive([("large-format.bin", b"small", deflated)], True),
        "traversal": archive([("../escape", b"x", stored)]),
        "absolute": archive([("/outside", b"x", stored)]),
        "colon": archive([("C:outside", b"x", stored)]),
        "dot_component": archive([("scripts/./bad", b"x", stored)]),
        "repeated_separator": archive([("scripts//bad", b"x", stored)]),
        "symlink": changed(single, central + 38, struct.pack("<I", 0o120777 << 16)),
        "bad_crc": changed(single, data_start, b"!"),
        "bad_local_name": changed(single, 30, b"!"),
        "short_output": changed(changed(single, 22, struct.pack("<I", 1)),
                                central + 24, struct.pack("<I", 1)),
        "long_output": changed(changed(single, 22, struct.pack("<I", 100)),
                               central + 24, struct.pack("<I", 100)),
    }
    duplicate = archive([("same.bin", b"broken", stored), ("same.bin", b"visible", deflated)])
    result["hidden_bad_crc"] = changed(duplicate, 30 + len("same.bin"), b"!")
    encrypted = changed(changed(single, 6, b"\x01\x00"), central + 8, b"\x01\x00")
    result["encrypted"] = encrypted
    unsupported = changed(changed(single, 8, b"\x0c\x00"), central + 10, b"\x0c\x00")
    result["unsupported"] = unsupported
    # Verify independent valid samples and malformed output/CRC behavior.
    for name in ("baseline", "single", "empty", "zip64", "zip64_local"):
        with zipfile.ZipFile(BytesIO(result[name])) as reader:
            assert reader.testzip() is None
    return result


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    arguments = parser.parse_args()
    rows = ["# Generated by Python zipfile; synthetic data only, not game content."]
    rows.extend(f"{name} {data.hex()}" for name, data in fixtures().items())
    expected = "\n".join(rows) + "\n"
    if arguments.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != expected:
            raise SystemExit("Archive fixtures differ; regenerate and review")
    else:
        OUTPUT.parent.mkdir(parents=True, exist_ok=True)
        OUTPUT.write_text(expected, encoding="utf-8", newline="\n")
    print(f"Verified {len(rows) - 1} independent synthetic archive fixtures")


if __name__ == "__main__":
    main()
