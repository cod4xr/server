"""Generate transport, command, and info fixtures from the pinned C source."""

import argparse
from pathlib import Path
import subprocess
import sys
import tempfile

from reference_source import ReferenceSource


ROOT = Path(__file__).resolve().parents[1]
FUNCTIONS = {
    "src/msg.c": (
        "MSG_Init", "MSG_WriteByte", "MSG_WriteShort", "MSG_WriteLong",
        "MSG_WriteData", "MSG_WriteBit0", "MSG_WriteBit1", "MSG_WriteBits",
        "MSG_BeginReading", "MSG_ClearLastReferencedEntity",
        "MSG_WriteEntityIndex", "MSG_ReadBit", "MSG_ReadBits",
        "MSG_ReadEntityIndex", "MSG_WriteString", "MSG_WriteBigString",
        "MSG_GetByte", "MSG_ReadByte", "MSG_ReadString"
    ),
    "src/netchan.c": (
        "Netchan_TransmitNextFragment", "Netchan_Transmit", "NET_OutOfBandPrint"
    ),
    "src/cmd.c": ("Cmd_TokenizeStringInternal",),
    "src/qshared.c": (
        "Info_RemoveKey", "Info_ValueForKey", "Info_SetValueForKey"
    ),
    "src/sv_client.c": ("SV_GetChallenge",),
}


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("reference", type=Path)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--cc", default="gcc")
    args = parser.parse_args()
    if sys.byteorder != "little":
        raise SystemExit("Upstream oracle requires a little-endian host")
    reference = ReferenceSource(args.reference)
    parts = [
        (ROOT / "tools/oracles/wire_preamble.h").read_text(encoding="utf-8"),
        (ROOT / "tools/oracles/challenge_preamble.h").read_text(encoding="utf-8"),
    ]
    for filename, functions in FUNCTIONS.items():
        for name in functions:
            parts.append(reference.function(filename, name))
    parts.append(
        (ROOT / "tools/oracles/wire_driver.c").read_text(encoding="utf-8")
    )
    with tempfile.TemporaryDirectory(prefix="cod4x-wire-oracle-") as scratch:
        directory = Path(scratch)
        source = directory / "oracle.c"
        source.write_text("\n\n".join(parts), encoding="utf-8")
        executable = directory / (
            "oracle.exe" if sys.platform == "win32" else "oracle"
        )
        subprocess.run(
            [args.cc, "-std=c11", "-O0", "-fno-strict-aliasing",
             str(source), "-o", str(executable)], check=True
        )
        rows = subprocess.check_output([str(executable)])
    rows = rows.replace(b"\r\n", b"\n")
    header = (
        "# Generated by tools/generate_wire_vectors.py; do not edit.\n"
        "# SPDX-License-Identifier: AGPL-3.0-or-later\n"
        f"# Upstream {reference.revision}; hashes in upstream.lock.json\n"
    ).encode("utf-8")
    output = ROOT / "crates/protocol/tests/fixtures/wire_vectors.txt"
    result = header + rows
    if args.check:
        if output.read_bytes() != result:
            raise SystemExit("Wire fixtures differ from the C oracle")
    else:
        output.write_bytes(result)
    print(f"Verified {len(rows.splitlines())} upstream wire fixtures")


if __name__ == "__main__":
    main()
