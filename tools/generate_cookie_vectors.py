"""Generate synthetic endpoint cookie vectors with independent Python HMAC."""

import argparse
import hashlib
import hmac
import ipaddress
from pathlib import Path
import struct


ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "crates/server-core/tests/fixtures/cookie_vectors.txt"
DOMAIN = b"cod4x-rust/legacy-endpoint-cookie/v1\0"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    keys = [bytes(range(32)), bytes(reversed(range(32))), bytes([0xa5]) * 32]
    addresses = [
        ("127.0.0.1", 28960, 0), ("192.0.2.1", 0, 0), ("192.0.2.1", 65535, 0),
        ("::ffff:192.0.2.1", 65535, 0), ("::1", 28960, 0),
        ("2001:db8::1", 28960, 0), ("fe80::1", 28960, 4), ("fe80::1", 28960, 5),
    ]
    rows = ["# Synthetic test keys only; generated by independent Python hmac/sha256."]
    for key in keys:
        for text, port, scope in addresses:
            address = ipaddress.ip_address(text)
            if isinstance(address, ipaddress.IPv6Address) and address.ipv4_mapped:
                address = address.ipv4_mapped
            message = DOMAIN + bytes([address.version]) + address.packed + struct.pack(">H", port)
            if address.version == 6:
                message += struct.pack(">I", scope)
            tag = hmac.new(key, message, hashlib.sha256).digest()[:4]
            challenge = int.from_bytes(tag, "little", signed=True)
            rows.append(f"{key.hex()} {text} {port} {scope} {challenge}")
    expected = "\n".join(rows) + "\n"
    if args.check:
        if OUTPUT.read_text(encoding="utf-8") != expected:
            raise SystemExit("Endpoint cookie fixtures differ")
    else:
        OUTPUT.parent.mkdir(parents=True, exist_ok=True)
        OUTPUT.write_text(expected, encoding="utf-8", newline="\n")
    print(f"Verified {len(rows) - 1} independent synthetic endpoint cookie vectors")


if __name__ == "__main__":
    main()
