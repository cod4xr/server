"""Decode deterministic wire commands with the original pinned C implementation."""

import argparse
from pathlib import Path
import re
import subprocess
import sys
import tempfile

from reference_source import ReferenceSource


ROOT = Path(__file__).resolve().parents[1]
FUNCTIONS = (
    "MSG_Init", "MSG_BeginReading", "MSG_GetByte", "MSG_GetShort", "MSG_GetLong", "MSG_ReadByte",
    "MSG_WriteByte", "MSG_WriteShort", "MSG_WriteBit0", "MSG_WriteBit1",
    "MSG_ReadShort", "MSG_ReadLong", "MSG_ReadBit", "MSG_ReadBits",
    "MSG_ReadKey", "MSG_ReadDeltaKeyShort", "MSG_ReadDeltaKeyByte",
    "MSG_ReadDeltaKey", "MSG_ReadForwardRightMove", "MSG_ReadDeltaUsercmdKey",
)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("reference", type=Path)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--cc", default="gcc")
    args = parser.parse_args()
    if sys.byteorder != "little":
        raise SystemExit("Upstream oracle requires a little-endian host")
    reference = ReferenceSource(args.reference)
    command = re.search(r"typedef struct usercmd_s\s*\{.*?\}\s*usercmd_t;",
                        reference.files["src/player.h"], re.DOTALL)
    masks = re.search(r"unsigned int kbitmask\[33\]\s*=\s*\{.*?\};",
                      reference.files["src/msg.c"], re.DOTALL)
    angle = re.search(r"(?m)^#define\s+ANGLE2SHORT[^\n]+", reference.files["src/q_math.h"])
    if not command or not masks or not angle:
        raise SystemExit("Original command declaration/mask/macro not found")
    parts = [
        (ROOT / "tools/oracles/wire_preamble.h").read_text(encoding="utf-8"),
        "#ifndef __cdecl\n#define __cdecl\n#endif\n#define CON_CHANNEL_SERVER 0",
        command.group(0), masks.group(0), angle.group(0),
    ]
    parts.extend(reference.function("src/msg.c", name) for name in FUNCTIONS)
    parts.append((ROOT / "tools/oracles/user_command_driver.c").read_text(encoding="utf-8"))
    with tempfile.TemporaryDirectory(prefix="cod4x-usercmd-oracle-") as scratch:
        directory = Path(scratch)
        source = directory / "oracle.c"
        source.write_text("\n\n".join(parts), encoding="utf-8")
        executable = directory / ("oracle.exe" if sys.platform == "win32" else "oracle")
        subprocess.run([
            args.cc, "-std=c11", "-O0", "-fno-strict-aliasing", "-fsigned-char", "-fwrapv",
            "-ffp-contract=off", "-fexcess-precision=standard", str(source), "-o", str(executable),
        ], check=True)
        rows = subprocess.check_output([str(executable)]).replace(b"\r\n", b"\n")
    expected = (
        "# Generated by tools/generate_user_command_vectors.py; do not edit.\n"
        "# SPDX-License-Identifier: AGPL-3.0-or-later\n"
        f"# Upstream {reference.revision}; hashes in upstream.lock.json\n"
    ).encode("utf-8") + rows
    output = ROOT / "crates/protocol/tests/fixtures/user_command_vectors.txt"
    if args.check:
        if output.read_bytes() != expected:
            raise SystemExit("User-command fixtures differ from the C oracle")
    else:
        output.write_bytes(expected)
    count = sum(not row.startswith(b"#") for row in rows.splitlines())
    print(f"Verified {count} original C user-command vectors and all 65536 melee angles")


if __name__ == "__main__":
    main()
