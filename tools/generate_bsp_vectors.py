"""Generate valid IBSP lookup/checksum evidence with pinned original C functions."""

import argparse
from pathlib import Path
import re
import subprocess
import sys
import tempfile

from reference_source import ReferenceSource


ROOT = Path(__file__).resolve().parents[1]
SOURCE = "src/com_bsp_load_obj.c"
FUNCTIONS = (
    "Com_IsBspLoaded", "Com_GetBspLumpCountForVersion", "Com_CheckVersionLumpCountError",
    "Com_BspError", "Com_ValidateBspLumpData", "Com_GetBspLump", "Com_GetBspVersion", "Com_BspHasLump",
)


def declaration(source: str, pattern: str) -> str:
    match = re.search(pattern, source, re.DOTALL)
    if not match:
        raise ValueError("Original BSP declaration not found")
    return match.group(0)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("reference", type=Path)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--cc", default="gcc")
    args = parser.parse_args()
    if sys.byteorder != "little":
        raise SystemExit("Original BSP oracle requires a little-endian host")
    reference = ReferenceSource(args.reference)
    source = reference.files[SOURCE]
    parts = [
        "#include <assert.h>\n#include <stddef.h>\n#include <stdint.h>\n"
        "#include <stdbool.h>\n#include <stdio.h>\n#include <stdlib.h>\n#include <string.h>\n"
        "#ifndef __cdecl\n#define __cdecl\n#endif\n#define Com_Error(...) abort()\n"
        "typedef unsigned char byte;",
        declaration(reference.files["src/cm_local.h"], r"enum LumpType\s*\{.*?\};"),
        declaration(source, r"unsigned int lumpsForVersion\[\]\s*=\s*\{.*?\};"),
        declaration(source, r"struct BspChunk\s*\{.*?\};"),
        declaration(source, r"typedef struct BspHeader\s*\{.*?\}\s*BspHeader;"),
        declaration(source, r"typedef struct comBspGlob_t\s*\{.*?\}\s*comBspGlob_t;"),
        "comBspGlob_t comBspGlob;",
    ]
    parts.extend(reference.function(SOURCE, name) for name in FUNCTIONS)
    parts.append(reference.function("src/filesystem.c", "Com_BlockChecksumKey32"))
    parts.append((ROOT / "tools/oracles/bsp_driver.c").read_text(encoding="utf-8"))
    with tempfile.TemporaryDirectory(prefix="cod4x-bsp-oracle-") as scratch:
        directory = Path(scratch)
        generated = directory / "oracle.c"
        generated.write_text("\n\n".join(parts), encoding="utf-8")
        executable = directory / ("oracle.exe" if sys.platform == "win32" else "oracle")
        subprocess.run([args.cc, "-std=c11", "-O0", "-fno-strict-aliasing", "-Wno-multichar",
                        str(generated), "-o", str(executable)], check=True)
        rows = subprocess.check_output([str(executable)]).replace(b"\r\n", b"\n")
    expected = (
        "# Generated by tools/generate_bsp_vectors.py; synthetic containers only.\n"
        "# SPDX-License-Identifier: AGPL-3.0-or-later\n"
        f"# Upstream {reference.revision}; hashes in upstream.lock.json\n"
    ).encode("utf-8") + rows
    output = ROOT / "crates/content/tests/fixtures/bsp_vectors.txt"
    if args.check:
        if output.read_bytes() != expected:
            raise SystemExit("BSP fixtures differ from original functions")
    else:
        output.write_bytes(expected)
    print(f"Verified {len(rows.splitlines())} original C BSP lookups across 40 versions")


if __name__ == "__main__":
    main()
