"""Run pinned filesystem C functions for byte paths and seeded IWD checksums."""

import argparse
from io import BytesIO
from pathlib import Path
import struct
import subprocess
import sys
import tempfile
import zipfile

from generate_archive_fixtures import fixtures
from reference_source import ReferenceSource


ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "crates/content/tests/fixtures/content_vectors.txt"


def c_array(data: bytes) -> str:
    return "{" + ",".join(str(byte) for byte in data or b"\0") + "}"


def driver() -> str:
    statements = []
    pairs = [
        (b"IMAGES/Badge.IWI", b"images/badge.iwi"),
        (b"images\\badge.iwi", b"images/badge.iwi"),
        (b"SCRIPTS\\main.GSC", b"scripts/main.gsc"),
        (b"images/a.iwi", b"images/b.iwi"),
        (b"images/\xff.iwi", b"IMAGES\\\xff.IWI"),
        (b"models/hero.v2", b"models/hero.v3"),
        (b"x" * 256, b"X" * 256),
    ]
    for index, (left, right) in enumerate(pairs):
        statements.extend([
            f"char left{index}[] = {c_array(left + bytes(1))};",
            f"char right{index}[] = {c_array(right + bytes(1))};",
            f'printf("path {left.hex()} {right.hex()} %d\\n", '
            f'FS_FilenameCompare(left{index}, right{index}) == 0);',
        ])
    for index, (label, data) in enumerate(fixtures().items()):
        if label not in {"baseline", "single", "empty", "zip64", "zip64_local"}:
            continue
        with zipfile.ZipFile(BytesIO(data)) as archive:
            crcs = b"".join(struct.pack("<I", entry.CRC) for entry in archive.infolist()
                            if entry.file_size != 0)
        statements.append(f"byte data{index}[] = {c_array(crcs)};")
        for feed in (0, 1, 0x12345678, 0x80000000, 0xffffffff):
            statements.extend([
                f"feed = {feed}u; memcpy(&key, &feed, sizeof(key));",
                f'printf("checksum {label} {feed:08x} %08x\\n", '
                f'Com_BlockChecksumKey32(data{index}, {len(crcs)}, key));',
            ])
    return "int main(void) { unsigned int feed; int key;\n" + "\n".join(statements) + "\n}"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("reference", type=Path)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--cc", default="gcc")
    args = parser.parse_args()
    if sys.byteorder != "little":
        raise SystemExit("Upstream oracle requires a little-endian host")
    reference = ReferenceSource(args.reference)
    parts = [
        "#include <stdio.h>\n#include <string.h>\n#include <limits.h>\n"
        "typedef unsigned char byte; typedef int qboolean;\n"
        '_Static_assert(sizeof(int) == 4 && CHAR_BIT == 8, "Original integer profile");',
        reference.function("src/filesystem.c", "FS_FilenameCompare"),
        reference.function("src/filesystem.c", "Com_BlockChecksumKey32"),
        driver(),
    ]
    with tempfile.TemporaryDirectory(prefix="cod4x-content-oracle-") as scratch:
        directory = Path(scratch)
        source = directory / "oracle.c"
        source.write_text("\n\n".join(parts), encoding="utf-8")
        executable = directory / ("oracle.exe" if sys.platform == "win32" else "oracle")
        subprocess.run([args.cc, "-std=c11", "-O0", str(source), "-o", str(executable)],
                       check=True)
        rows = subprocess.check_output([str(executable)]).replace(b"\r\n", b"\n")
    header = (
        "# Generated by tools/generate_content_vectors.py; do not edit.\n"
        "# SPDX-License-Identifier: AGPL-3.0-or-later\n"
        f"# Upstream {reference.revision}; hashes in upstream.lock.json\n"
    ).encode("utf-8")
    expected = header + rows
    if args.check:
        if OUTPUT.read_bytes() != expected:
            raise SystemExit("Content fixtures differ from original C functions")
    else:
        OUTPUT.write_bytes(expected)
    print(f"Verified {len(rows.splitlines())} original C content vectors")


if __name__ == "__main__":
    main()
